"""docs/generated-index: {language}/docs/README.md is current.

The index is generated by uc-automa docs index (uc-automa 0009) and
never edited by hand; this check regenerates it and compares.
"""

from __future__ import annotations

from ..docs import IndexError_, render_index
from . import Repository, check


@check("conformance.docs.generated_index", "docs/generated-index")
def generated_index(repo: Repository):
    if repo.config is None:
        return []
    language = repo.config.language
    rel = f"{language}/docs/README.md"
    try:
        wanted = render_index(repo.root, language, repo.files)
    except IndexError_ as exc:
        return [(rel, str(exc))]
    path = repo.path(rel)
    if not path.is_file():
        return [(rel, "missing; run uc-automa docs index")]
    if path.read_text(encoding="utf-8") != wanted:
        return [(rel, "out of date or edited by hand; run uc-automa docs "
                      "index")]
    return []
